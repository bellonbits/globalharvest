/**
 * Generates the dotted world map used by <GlobalMap />.
 * Output is a compact list of dot coordinates so no map library ships to the browser.
 * Usage: node scripts/generate-world-map.mjs
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import DottedMap from 'dotted-map'

const ROOT = path.resolve(import.meta.dirname, '..')
const map = new DottedMap({ height: 56, grid: 'diagonal' })
const points = map.getPoints()
const xs = points.map((p) => p.x)
const ys = points.map((p) => p.y)
const width = Math.ceil(Math.max(...xs)) + 1
const height = Math.ceil(Math.max(...ys)) + 1
const flat = points.map((p) => `${+p.x.toFixed(2)},${+p.y.toFixed(2)}`).join(' ')

await fs.writeFile(
  path.join(ROOT, 'src/content/worldDots.generated.ts'),
  `// Generated by scripts/generate-world-map.mjs — do not edit by hand.
export const WORLD_WIDTH = ${width}
export const WORLD_HEIGHT = ${height}
/** Space-separated "x,y" dot centres on a ${width}×${height} grid. */
export const WORLD_DOTS = '${flat}'
`,
)
console.log(`${points.length} dots, ${width}x${height}`)
